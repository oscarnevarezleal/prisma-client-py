"""Benchmark harness: cost of using the sync **and** async clients together.

`interface` is a whole-client generator option, so an app that needs both a
blocking and an asyncio entrypoint has to generate the client twice into two
packages. This harness measures what that second package actually costs, and
compares it against a *unified* layout where both interfaces share one copy of
`models.py` / `types.py` / `bases.py` and only the action + client layers are
duplicated.

For an identical synthetic schema it reports, per layout:

  * generated on-disk size of the runtime .py files
  * how many generated bytes are byte-identical between the sync and async build
  * retained RSS after importing the first client, and the *marginal* RSS added
    by bringing up the second interface

The unified layout is built by grafting the sync build's `actions.py` /
`client.py` onto the async build's package as `actions_sync.py` /
`client_sync.py`, rewiring their relative imports. That is a prototype of the
proposed generator change, not a supported output — it exists so the saving can
be measured rather than estimated.

Example:
    python benchmarks/dual_interface.py --models 20 50 --repeats 3
"""

from __future__ import annotations

import os
import sys
import json
import shutil
import hashlib
import argparse
import subprocess
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Modules imported to bring a client fully up. `client` transitively pulls in
# `types`, `models` and `actions`, which is where essentially all of the cost is.
IMPORT_TARGET = 'client'

# Files that differ between a sync and an async build. Everything else the
# generator emits is byte-identical, which is the premise being measured.
INTERFACE_SPECIFIC = {
    'actions.py',
    'client.py',
    'http.py',
    'engine/abstract.py',
    'engine/query.py',
    'engine/http.py',
}


def _run(cmd: list[str], **kwargs: object) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kwargs)  # type: ignore[arg-type]


# --------------------------------------------------------------------------- #
# generation
# --------------------------------------------------------------------------- #
def generate(workdir: Path, pkg: str, interface: str, models: int, recursive_type_depth: int, minimal_runtime: bool) -> Path:
    """Generate one client into `workdir/pkg` and return its path."""
    schema = workdir / f'{pkg}.prisma'
    _run(
        [
            sys.executable,
            str(HERE / 'gen_schema.py'),
            '--models', str(models),
            '--output', f'./{pkg}',
            '--schema', str(schema),
            '--interface', interface,
            '--recursive-type-depth', str(recursive_type_depth),
        ]
    )
    if minimal_runtime:
        text = schema.read_text()
        text = text.replace('generator client {', 'generator client {\n  minimalRuntime       = true')
        schema.write_text(text)

    # The harness never connects to a database or runs a query, so the query
    # engine version is irrelevant; DEBUG_GENERATOR skips the version guard that
    # would otherwise trip on a Prisma CLI / package hash mismatch.
    env = {k: v for k, v in os.environ.items() if not k.startswith('PRISMA_PY_CONFIG_')}
    env['PRISMA_PY_DEBUG_GENERATOR'] = '1'
    _run([sys.executable, '-m', 'prisma', 'generate', f'--schema={schema}'], cwd=workdir, env=env)
    return workdir / pkg


def build_unified(async_pkg: Path, sync_pkg: Path, dest: Path) -> Path:
    """Graft the sync build's interface-specific layers onto the async package.

    The result has one copy of the Pydantic models, the query types and the
    bases, plus two action/client layers -- i.e. what the generator would emit if
    `interface` produced both flavours into a single package.
    """
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(async_pkg, dest, ignore=shutil.ignore_patterns('__pycache__'))

    actions = (sync_pkg / 'actions.py').read_text().replace(
        'from .client import Prisma',
        'from .client_sync import Prisma',
    )
    client = (sync_pkg / 'client.py').read_text().replace(
        'from . import types, models, errors, actions',
        'from . import types, models, errors\nfrom . import actions_sync as actions',
    )
    (dest / 'actions_sync.py').write_text(actions)
    (dest / 'client_sync.py').write_text(client)
    return dest


# --------------------------------------------------------------------------- #
# measurement
# --------------------------------------------------------------------------- #
MEASURE_SRC = """
import sys, gc, importlib

def rss_mb():
    with open('/proc/self/statm') as f:
        return int(f.read().split()[1]) * 4096 / 1024 / 1024

steps = []
prev = rss_mb()
for spec in sys.argv[1:]:
    importlib.import_module(spec)
    gc.collect()
    cur = rss_mb()
    steps.append(round(cur - prev, 2))
    prev = cur
print(steps)
"""


def measure_rss(workdir: Path, specs: list[str]) -> list[float]:
    """Retained RSS added by each import step, in order.

    Uses statm (current RSS) rather than ru_maxrss: we want what stays resident
    once both clients are up, not the transient peak while Pydantic builds them.
    Bytecode caches are warmed first, otherwise compiling the multi-megabyte
    `types.py` from source dominates and swamps the signal.
    """
    script = workdir / '_measure.py'
    script.write_text(MEASURE_SRC)
    _run([sys.executable, '-c', 'import ' + ', '.join(specs)], cwd=workdir)  # warm __pycache__
    out = _run([sys.executable, str(script), *specs], cwd=workdir).stdout
    return json.loads(out.strip())


def measure_size_kb(pkg: Path) -> float:
    """Total size of the runtime .py files (.pyi stubs aren't imported)."""
    return sum(f.stat().st_size for f in pkg.rglob('*.py')) / 1024


def measure_overlap(async_pkg: Path, sync_pkg: Path) -> dict[str, float]:
    """How many generated bytes are byte-identical across the two builds."""
    identical_kb = differing_kb = 0.0
    for path in async_pkg.rglob('*.py'):
        rel = path.relative_to(async_pkg)
        other = sync_pkg / rel
        kb = path.stat().st_size / 1024
        if other.exists() and hashlib.md5(path.read_bytes()).digest() == hashlib.md5(other.read_bytes()).digest():
            identical_kb += kb
        else:
            differing_kb += kb
    total = identical_kb + differing_kb
    return {
        'identical_kb': round(identical_kb, 1),
        'differing_kb': round(differing_kb, 1),
        'identical_pct': round(identical_kb / total * 100, 1) if total else 0.0,
    }


# --------------------------------------------------------------------------- #
# driver
# --------------------------------------------------------------------------- #
def run_case(workdir: Path, models: int, repeats: int, recursive_type_depth: int, minimal_runtime: bool) -> dict[str, object]:
    suffix = f'{models}{"mr" if minimal_runtime else ""}'
    async_pkg = generate(workdir, f'p{suffix}_async', 'asyncio', models, recursive_type_depth, minimal_runtime)
    sync_pkg = generate(workdir, f'p{suffix}_sync', 'sync', models, recursive_type_depth, minimal_runtime)
    unified = build_unified(async_pkg, sync_pkg, workdir / f'p{suffix}_unified')

    separate = [
        measure_rss(workdir, [f'{async_pkg.name}.{IMPORT_TARGET}', f'{sync_pkg.name}.{IMPORT_TARGET}'])
        for _ in range(repeats)
    ]
    joined = [
        measure_rss(workdir, [f'{unified.name}.{IMPORT_TARGET}', f'{unified.name}.{IMPORT_TARGET}_sync'])
        for _ in range(repeats)
    ]

    def median_at(runs: list[list[float]], idx: int) -> float:
        return round(statistics.median(r[idx] for r in runs), 1)

    return {
        'models': models,
        'minimal_runtime': minimal_runtime,
        'recursive_type_depth': recursive_type_depth,
        'overlap': measure_overlap(async_pkg, sync_pkg),
        'size_kb': {
            'separate': round(measure_size_kb(async_pkg) + measure_size_kb(sync_pkg), 1),
            'unified': round(measure_size_kb(unified), 1),
        },
        'rss_mb': {
            'separate_first': median_at(separate, 0),
            'separate_second': median_at(separate, 1),
            'unified_first': median_at(joined, 0),
            'unified_second': median_at(joined, 1),
        },
    }


def report(results: list[dict[str, object]]) -> None:
    print()
    print('marginal cost of the second interface (retained RSS, MB)')
    print()
    print('| models | minimalRuntime | first client | +2nd, separate pkgs | +2nd, unified | total sep → uni | saving |')
    print('| ---: | :-: | ---: | ---: | ---: | ---: | ---: |')
    for r in results:
        rss = r['rss_mb']  # type: ignore[index]
        sep_total = rss['separate_first'] + rss['separate_second']
        uni_total = rss['unified_first'] + rss['unified_second']
        pct = (sep_total - uni_total) / sep_total * 100 if sep_total else 0.0
        print(
            f'| {r["models"]} | {"yes" if r["minimal_runtime"] else "no"} '
            f'| {rss["separate_first"]:.1f} | {rss["separate_second"]:.1f} | {rss["unified_second"]:.1f} '
            f'| {sep_total:.1f} → {uni_total:.1f} | −{pct:.0f}% |'
        )

    print()
    print('generated runtime .py bytes')
    print()
    print('| models | minimalRuntime | identical across sync/async | separate total | unified total |')
    print('| ---: | :-: | ---: | ---: | ---: |')
    for r in results:
        ov, size = r['overlap'], r['size_kb']  # type: ignore[index]
        print(
            f'| {r["models"]} | {"yes" if r["minimal_runtime"] else "no"} | {ov["identical_pct"]:.1f}% '
            f'| {size["separate"] / 1024:.1f} MB | {size["unified"] / 1024:.1f} MB |'
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--models', type=int, nargs='+', default=[20], help='schema sizes to measure')
    parser.add_argument('--repeats', type=int, default=3, help='measurement repeats (median reported)')
    parser.add_argument('--recursive-type-depth', type=int, default=5)
    parser.add_argument('--minimal-runtime', action='store_true', help='also measure with minimalRuntime enabled')
    parser.add_argument('--workdir', default=None, help='where to generate (default: a temp dir next to this file)')
    parser.add_argument('--json', default=None, help='write raw results here')
    args = parser.parse_args()

    workdir = Path(args.workdir) if args.workdir else HERE / '.dual_interface'
    workdir.mkdir(parents=True, exist_ok=True)

    results = []
    for models in args.models:
        results.append(run_case(workdir, models, args.repeats, args.recursive_type_depth, minimal_runtime=False))
        if args.minimal_runtime:
            results.append(run_case(workdir, models, args.repeats, args.recursive_type_depth, minimal_runtime=True))

    report(results)

    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=2))
        print(f'\nwrote {args.json}')


if __name__ == '__main__':
    main()
